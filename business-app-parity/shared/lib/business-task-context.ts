/** Read-only task context from already authenticated Business owner records.
 * A task's marker is only a note, never proof a yard sign was collected
 * or a Google review was received. No writes or extra network requests.
 */
export type TaskContextRecord={id:string;customerId?:string|null;title:string;status:string;dueAt?:string|null;notes?:string|null};
export type TaskContextCustomer={id:string;name:string;phone?:string|null;email?:string|null;address?:string|null};
export type TaskContextEstimate={customerId:string;status:string};
export type TaskLinkedFlag={kind:"sign"|"review";recordedAt:string};
export function taskLinkedFlag(task:Pick<TaskContextRecord,"customerId"|"notes">):TaskLinkedFlag|null{
 if(!task.customerId||typeof task.notes!=="string")return null;
 const notes=task.notes.trim();
 const sign="FIRE yard sign placement: ",review="FIRE review request: ";
 // Ambiguous task descriptions must never route to an unrelated manual flag.
 if(notes.includes(sign)&&notes.includes(review))return null;
 const kind=notes.includes(sign)?"sign":notes.includes(review)?"review":null;
 if(!kind)return null;
 const marker=kind==="sign"?sign:review;
 const start=notes.lastIndexOf(marker);
 const timestamp=notes.slice(start+marker.length).trim();
 if(start<0||!timestamp||timestamp.length>64||!Number.isFinite(Date.parse(timestamp)))return null;
 // The reference event is deliberately at the end of an autogenerated draft.
 if(notes.slice(start)!==marker+timestamp)return null;
 return {kind,recordedAt:timestamp};
}
export function businessTaskContext(
 task:TaskContextRecord,customers:readonly TaskContextCustomer[],estimates:readonly TaskContextEstimate[]
){
 const customer=task.customerId?customers.find(x=>x.id===task.customerId)??null:null;
 const related=customer?estimates.filter(e=>e.customerId===customer.id):[];
 return {
  customer,flag:customer?taskLinkedFlag(task):null,
  estimateCount:related.length,
  scheduledCount:related.filter(e=>e.status==="scheduled").length,
  completedCount:related.filter(e=>e.status==="completed").length
 };
}
