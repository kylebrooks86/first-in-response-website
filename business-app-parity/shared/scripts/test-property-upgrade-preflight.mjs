import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {mkdtempSync,readFileSync,writeFileSync,existsSync,rmSync,cpSync,mkdirSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {createHash} from 'node:crypto';
import {loadPropertyUpgrade,capturePropertyUpgradeMetadata,evaluatePropertyUpgrade,inspectPropertyUpgradeFile} from './property-upgrade-preflight.mjs';
const repo=resolve(process.argv[2]??'../..'),manifest=join(repo,'business-app-parity/release/property-upgrade/manifest.json');
const temp=mkdtempSync(join(tmpdir(),'fire-schema-preflight-'));let passed=0;const checks=[];
const check=(name,fn)=>{fn();passed++;checks.push(name);};
const hash=path=>createHash('sha256').update(readFileSync(path)).digest('hex');
try{
 for(const target of ['live','doomsday','staging']){
  const root=join(repo,'business-app-parity/adapters',target),pkg=loadPropertyUpgrade(root,manifest,target);
  const altered=join(temp,target+'-manifest'),copyRoot=join(temp,target+'-root');
  mkdirSync(altered);cpSync(join(repo,'business-app-parity/release/property-upgrade'),altered,{recursive:true});
  const alteredManifest=join(altered,'manifest.json'),firstPlan=pkg.planned[0];
  writeFileSync(join(altered,target,firstPlan.name),firstPlan.sql+'\n-- altered bytes');
  check(target+' planned checksum tampering blocks',()=>assert.throws(()=>loadPropertyUpgrade(root,alteredManifest,target),/checksum/));
  cpSync(root,copyRoot,{recursive:true});writeFileSync(join(copyRoot,'drizzle',pkg.baselineNames[0]),'-- modified history');
  check(target+' historical migration changes block',()=>assert.throws(()=>loadPropertyUpgrade(copyRoot,manifest,target),/checksum/));
  const db=new DatabaseSync(':memory:');db.exec('PRAGMA foreign_keys=ON');
  for(const file of pkg.plan.baseline)db.exec(readFileSync(join(root,'drizzle',file.name),'utf8'));
  db.exec('CREATE TABLE d1_migrations(id INTEGER PRIMARY KEY,name TEXT NOT NULL,applied_at TEXT)');
  const addJournal=name=>db.prepare('INSERT INTO d1_migrations(name) VALUES(?)').run(name);
  pkg.baselineNames.forEach(addJournal);
  const capture=()=>capturePropertyUpgradeMetadata({all:s=>db.prepare(s).all(),get:s=>db.prepare(s).get()},root);
  const report=()=>capture().then(m=>evaluatePropertyUpgrade(m,pkg));
  let m=await capture(),r=evaluatePropertyUpgrade(m,pkg);
  check(target+' exact baseline review eligible',()=>assert.equal(r.eligibleForSeparatelyApprovedUpgrade,true));
  check(target+' no execution or release authority',()=>assert.equal(r.productionReady||r.executionAuthorized||r.remoteVerified||r.schemaRemovalAuthorized,false));
  const bad=mutate=>{const c=structuredClone(m);mutate(c);return evaluatePropertyUpgrade(c,pkg);};
  check(target+' missing journal blocked',()=>assert.equal(bad(c=>c.journal=null).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' incomplete journal blocked',()=>assert.equal(bad(c=>c.journal.pop()).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' duplicate journal blocked',()=>assert.equal(bad(c=>c.journal.push(c.journal[0])).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' financial collision blocked',()=>assert.equal(bad(c=>c.financialCounts[0]=1).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' unreadable financial query blocked',()=>assert.equal(bad(c=>c.financialCounts[1]=null).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' FK disabled blocked',()=>assert.equal(bad(c=>c.foreignKeysEnabled=false).eligibleForSeparatelyApprovedUpgrade,false));
  check(target+' FK violations blocked',()=>assert.equal(bad(c=>c.foreignKeyViolations=1).eligibleForSeparatelyApprovedUpgrade,false));
  db.exec(pkg.planned[0].sql);addJournal(pkg.planned[0].name);r=await report();
  check(target+' partial installation blocked',()=>assert.equal(r.propertySchemaState==='partial'&&!r.eligibleForSeparatelyApprovedUpgrade&&!r.candidatePropertySchemaReady,true));
  db.exec(pkg.planned[1].sql);addJournal(pkg.planned[1].name);m=await capture();r=evaluatePropertyUpgrade(m,pkg);
  check(target+' complete exact candidate ready',()=>assert.equal(r.candidatePropertySchemaReady,true));
  check(target+' empty candidate legacy rollback review compatible',()=>assert.equal(r.legacyAppRollbackCompatible,true));
  check(target+' changed literal whitespace cannot normalize away',()=>{const c=structuredClone(m),trigger=c.schema.find(x=>x.name==='customer_property_no_delete');trigger.sql=trigger.sql.replace('history must','history  must');assert.equal(evaluatePropertyUpgrade(c,pkg).candidatePropertySchemaReady,false);});
  check(target+' corrupted property data blocks',()=>assert.equal(bad(c=>c.propertyAnomalies[2]=1).candidatePropertySchemaReady,false));
  check(target+' unreleased recovery guard blocks',()=>assert.equal(bad(c=>c.extensionCounts.property_recovery_guard=1).candidatePropertySchemaReady,false));
  db.prepare("INSERT INTO customers(id,name,created_at) VALUES('c','Synthetic','2026-10-14')").run();
  db.prepare("INSERT INTO customer_properties(id,customer_id,address,created_at) VALUES('p','c','123 Test','2026-10-14')").run();r=await report();
  check(target+' retained properties prohibit legacy rollback',()=>assert.equal(r.candidatePropertySchemaReady&&!r.legacyAppRollbackCompatible,true));
  db.exec('DROP TRIGGER customer_property_no_delete');r=await report();
  check(target+' missing immutable trigger blocks',()=>assert.equal(r.candidatePropertySchemaReady,false));
  db.exec("CREATE TRIGGER customer_property_no_delete BEFORE DELETE ON customer_properties BEGIN SELECT 1; END");r=await report();
  check(target+' same-name weak trigger blocks',()=>assert.equal(r.candidatePropertySchemaReady,false));
  db.exec('CREATE TABLE unexpected_records(id TEXT)');r=await report();
  check(target+' unexpected schema blocked',()=>assert.equal(r.schemaDifferences.includes('unexpected:table:unexpected_records'),true));
  db.close();
  const path=join(temp,target+'.sqlite'),writer=new DatabaseSync(path);
  writer.exec('PRAGMA journal_mode=WAL; PRAGMA wal_autocheckpoint=0');
  for(const file of pkg.plan.baseline)writer.exec(readFileSync(join(root,'drizzle',file.name),'utf8'));
  writer.exec('CREATE TABLE d1_migrations(id INTEGER PRIMARY KEY,name TEXT NOT NULL)');
  pkg.baselineNames.forEach(n=>writer.prepare('INSERT INTO d1_migrations(name) VALUES(?)').run(n));
  const beforeMain=hash(path),beforeWal=hash(path+'-wal');
  r=await inspectPropertyUpgradeFile(path,root,manifest,target);
  check(target+' committed WAL baseline visible',()=>assert.equal(r.eligibleForSeparatelyApprovedUpgrade,true));
  writer.exec(pkg.planned[0].sql);
  const partialMain=hash(path),partialWal=hash(path+'-wal');
  r=await inspectPropertyUpgradeFile(path,root,manifest,target);
  check(target+' committed WAL partial schema blocked',()=>assert.equal(r.propertySchemaState,'partial'));
  check(target+' reader changes no database or WAL bytes',()=>{assert.equal(hash(path),partialMain);assert.equal(hash(path+'-wal'),partialWal);assert.equal(beforeMain,partialMain);assert.notEqual(beforeWal,partialWal);});
  writer.close();
  const absent=join(temp,target+'-missing.sqlite');
  await assert.rejects(inspectPropertyUpgradeFile(absent,root,manifest,target));
  check(target+' missing destination never created',()=>assert.equal(existsSync(absent),false));
 }
 console.log(JSON.stringify({passed,total:checks.length,checks,scope:'LOCAL SQLite; no hosted identity or release acceptance'},null,2));
}finally{rmSync(temp,{recursive:true,force:true});}
