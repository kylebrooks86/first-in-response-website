import assert from "node:assert/strict";
import {DatabaseSync} from "node:sqlite";
import {schemaSql,enrollVerifiedDevice,checkTrustedDevicePin,revokeDevice} from "./shared/lib/trusted-device-store.mjs";
const sql=new DatabaseSync(":memory:");
sql.exec(schemaSql);
const db={prepare(query){return {bind(...args){const s=sql.prepare(query);return {async run(){const r=s.run(...args);return {success:true,meta:{changes:Number(r.changes)}}},async first(){return s.get(...args)||null}}}}}};
const now=1800000000,secret="synthetic-only-trusted-device-secret-0123456789",scope="qa",pin="0123";
const options={now,secret,scope,pin,ownerProofVerified:true};
let count=0;
async function equal(actual,expected){assert.equal(await actual,expected);count++}
await assert.rejects(enrollVerifiedDevice(db,{...options,ownerProofVerified:false}));count++;
await assert.rejects(enrollVerifiedDevice(db,{...options,pin:"12345"}));count++;
const device=await enrollVerifiedDevice(db,options);
const params={...options,token:device.token};
await equal(device.expiresAt,now+30*86400);
await equal(sql.prepare("SELECT count(*) AS n FROM fire_trusted_devices").get().n,1);
const row=sql.prepare("SELECT * FROM fire_trusted_devices").get();
assert.notEqual(row.device_key,device.token);assert.notEqual(row.pin_verifier,pin);count+=2;
await equal(checkTrustedDevicePin(db,{...params,scope:"dr"}),false);
await equal(checkTrustedDevicePin(db,{...params,token:"0".repeat(64)}),false);
await equal(checkTrustedDevicePin(db,{...params,pin:"12345"}),false);
await equal(sql.prepare("SELECT attempts FROM fire_trusted_devices").get().attempts,0);
await equal(checkTrustedDevicePin(db,params),true);
for(let i=0;i<4;i++)await equal(checkTrustedDevicePin(db,{...params,pin:"9999"}),false);
await equal(checkTrustedDevicePin(db,params),false);
await equal(checkTrustedDevicePin(db,{...params,now:now+1799}),false);
await equal(checkTrustedDevicePin(db,{...params,now:now+1800}),true);
await equal(sql.prepare("SELECT attempts FROM fire_trusted_devices").get().attempts,1);
await equal(revokeDevice(db,{...params,now:now+1801}),true);
await equal(checkTrustedDevicePin(db,{...params,now:now+1802}),false);
await equal(revokeDevice(db,{...params,now:now+1802}),false);
const expired=await enrollVerifiedDevice(db,options);
await equal(checkTrustedDevicePin(db,{...params,token:expired.token,now:expired.expiresAt}),false);
const concurrent=await enrollVerifiedDevice(db,options);
const results=await Promise.all(Array.from({length:20},()=>checkTrustedDevicePin(db,{...params,token:concurrent.token,pin:"9999"})));
assert.ok(results.every(x=>x===false));count++;
await equal(sql.prepare("SELECT max(attempts) AS n FROM fire_trusted_devices").get().n,5);
await equal(checkTrustedDevicePin(db,{...params,token:concurrent.token}),false);
sql.close();
console.log("PASS "+count+" SQLite trusted-device enrollment, isolation, expiration, attempt limits and revocation checks (offline only)");
