/** Focused source-only test of guarded EXISTING DR/NEW LIVE DARK updater. */
import assert from 'node:assert/strict';
import {spawnSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {existsSync,readFileSync,writeFileSync,rmSync,mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {TARGETS,inspectExistingDarkUpdateArchive} from './owner_existing_dark_code_update_once_approved.mjs';
const script=fileURLToPath(new URL('./owner_existing_dark_code_update_once_approved.mjs',import.meta.url));
const source=readFileSync(script,'utf8');
const sha=s=>createHash('sha256').update(s).digest('hex');
let done=0;
const ok=(x,why)=>{assert.ok(x,why);done++};
const denied=(f,why)=>{assert.throws(f,/FIRE EXISTING DARK UPDATE STOP/,why);done++};
const run=(...args)=>spawnSync(process.execPath,[script,...args],{
 encoding:'utf8',env:{...process.env,CI:'true',GITHUB_ACTIONS:'true'}
});
ok(Object.keys(TARGETS).sort().join(',')==='dr,new-live','two exact existing targets');
ok(TARGETS.dr.uuid!==TARGETS['new-live'].uuid,'independent D1 physical isolation');
ok(TARGETS.dr.previousVersion==='b7c42773-5a93-4c6c-91d2-83cdb8e857d9'&&
  TARGETS['new-live'].previousVersion==='adb5fd7c-ddd0-4e97-87e7-6a4045d42d09',
  'different already-created predecessor Worker versions');
ok(source.includes("getHostedState(target);")&&
  source.includes("versionStillSame(runWrangler(['deployments','status'")&&
  source.indexOf('writeLock(lock,')<source.indexOf("const updated=runWrangler(['deploy','--no-bundle'"),
  'fresh remote readback and durable lock happen before provider update');
ok(source.includes("if(process.platform!=='win32'||!process.stdin.isTTY")&&
  source.includes('process.env.CI||process.env.GITHUB_ACTIONS'),
  'remote update impossible in CI/noninteractive/non-Windows');
ok(source.includes("const required='UPDATE EXISTING DARK '")&&
  source.includes('typed!==required')&&source.includes("if(existsSync(workspace))stop"),
  'new per-target exact-source typed approval and nonreplay workspace');
ok(source.includes('rmSync(workspace,{recursive:true,force:true})')&&
  source.includes('if(!existsSync(lock))'),
  'cleanup only before durable provider-attempt lock');
ok(!source.includes('wrangler@latest')&&source.includes("'--no-install','wrangler@4.162.0'"),
  'Wrangler fixed with no package install');
const invalid=run('--publish','dr','untrusted.zip');
ok(invalid.status!==0&&/owner Acer Windows/.test(invalid.stderr),
  'no provider action possible from CI even with --publish');
const wrong=run('inspect','staging','example.zip');
ok(wrong.status!==0&&/usage:/.test(wrong.stderr),'unknown target denied');
const missing=run('inspect','dr',join(tmpdir(),'nonexisting-fire-no-assets.zip'));
ok(missing.status!==0&&/saved archive must exist/.test(missing.stderr),
  'no archive preflight fails closed');
let ownerFiles=0;
const folder=mkdtempSync(join(tmpdir(),'fire-update-offline-'));
try{
 for(const [target,key] of [['dr','FIRE_FROZEN_EXISTING_DARK_DR_ZIP'],
                             ['new-live','FIRE_FROZEN_EXISTING_DARK_NEW_LIVE_ZIP']]){
  if(!process.env[key])continue;
  const path=process.env[key];
  ok(existsSync(path),'optional owner saved ZIP exists, never generated by test');
  const r=inspectExistingDarkUpdateArchive(target,path);
  ok(r.filesVerified===243&&r.sourceSha==='15bd714c435a585f695ed7166cf06d2c31ea1a8e'&&
     r.authBlocked&&r.r2Disabled&&r.routesDisabled&&r.providerContacted===false&&
     r.allowedToPublish===false,target+' real exact archive offline verified with 243 byte-checked ZIP members');
  denied(()=>inspectExistingDarkUpdateArchive(target==='dr'?'new-live':'dr',path),
    target+' archive cannot be substituted for other Worker');
  const copy=Buffer.from(readFileSync(path));copy[Math.floor(copy.length/2)]^=1;
  const corrupt=join(folder,target+'-tampered.zip');writeFileSync(corrupt,copy);
  denied(()=>inspectExistingDarkUpdateArchive(target,corrupt),
    target+' modified current source ZIP rejected before extraction/provider');
  ok(sha(readFileSync(path))===TARGETS[target].sha,target+' reviewed original SHA pin verified');
  ownerFiles++;
 }
}finally{rmSync(folder,{recursive:true,force:true})}
console.log('PASS '+done+'/'+done+' focused EXISTING DARK code-update safety tests; owner-source ZIP archives '+ownerFiles+'/2 available. ZERO provider calls.');
